        versionName = "1.0"

        val tmdbApiKey = run {
            val envFile = rootProject.file(".env")
            if (envFile.exists()) {
                envFile.readLines()
                    .firstOrNull { it.startsWith("TMDB_API_KEY=") }
                    ?.removePrefix("TMDB_API_KEY=")
                    ?.trim()
                    ?: (project.findProperty("TMDB_API_KEY") as? String ?: "")
            } else {
                project.findProperty("TMDB_API_KEY") as? String ?: ""
            }
        }
        buildConfigField("String", "TMDB_API_KEY", "\"$tmdbApiKey\"")
    }

